#!/usr/bin/env python3
"""Measure the existing gallery entries without changing its membership or captions.

Run after changing gallery images: python3 tools/build_gallery_dimensions.py
Requires Pillow. The browser also corrects dimensions on load for replaced files.
"""
import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent


def main():
    paths = re.findall(r'src: "([^"]+)"', (ROOT / 'data/gallery-manifest.js').read_text())
    entries = []
    for path in paths:
        with Image.open(ROOT / path) as image:
            width, height = image.size
            if image.getexif().get(274) in (5, 6, 7, 8):
                width, height = height, width
        entries.append(f'  {json.dumps(path)}: [{width}, {height}]')
    (ROOT / 'data/gallery-dimensions.js').write_text(
        '// Generated by tools/build_gallery_dimensions.py; EXIF-oriented dimensions.\n'
        'window.__HOOKE_GALLERY_DIMENSIONS__ = {\n' + ',\n'.join(entries) + '\n};\n'
    )
    print(f'Measured {len(entries)} gallery images.')


if __name__ == '__main__':
    main()
